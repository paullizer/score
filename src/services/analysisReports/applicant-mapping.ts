import type { AnalysisReport, ReportApplicantIdentity, ReportCandidate, ReportGenerationOptions } from '../../domain/analysis-reports'
import { REPORT_LIMITS } from '../../domain/analysis-reports'
import { assertReportResourceLimits } from './model'
import { reportLimits, reportGenerationPolicy } from './policy'
import { assertXmlText } from './presentation'

export const MAPPING_LIMITS = {
  fileBytes: 5 * 1024 * 1024, expandedBytes: 16 * 1024 * 1024, entries: 256,
  sheets: 20, rows: 10_000, columns: 50, cells: 200_000, cellCharacters: 4096,
  identifierCharacters: 512, nameCharacters: 300, milliseconds: 30_000,
} as const

export type MappingCell = string | null | { unsupported: true }
export interface MappingSheet { name: string; rows: MappingCell[][] }
export interface MappingWorkbook { sheets: MappingSheet[] }
export interface ApplicantMappingRow { identifier: string; name: string | null }
export class MappingInputError extends Error {}
export const LOCAL_MAPPING_NOTICE = 'Applicant names were attached locally from an HR-selected mapping, not verified or generated by AI. Unmatched applicants retain their identifiers. Saved assessment text is unchanged. This download may contain personal information; share only with authorized reviewers.'

export function applicantIdentifier(source: string): string {
  return source.trim().replace(/\.(?:pdf|docx|doc|md|markdown)$/i, '')
}

function field(value: string, maximum: number, description: string): string {
  const text = value.trim()
  if (!text || text.length > maximum || /[\p{Cc}\p{Cf}\p{Zl}\p{Zp}]/u.test(text)) {
    throw new Error(`${description} must be nonempty, single-line plain text within the displayed length limit.`)
  }
  assertXmlText(text, description)
  return text
}

export function mappingRows(sheet: MappingSheet, header: number, identifierColumn: number, nameColumn: number): ApplicantMappingRow[] {
  if (!Number.isInteger(header) || header < 0 || header >= sheet.rows.length ||
    !Number.isInteger(identifierColumn) || !Number.isInteger(nameColumn) ||
    identifierColumn < 0 || nameColumn < 0 || identifierColumn >= MAPPING_LIMITS.columns ||
    nameColumn >= MAPPING_LIMITS.columns || identifierColumn === nameColumn) {
    throw new Error('Choose a header row and different identifier and full-name columns.')
  }
  const result: ApplicantMappingRow[] = []
  const seen = new Set<string>()
  for (let index = header + 1; index < sheet.rows.length; index++) {
    const row = sheet.rows[index]
    if (row.every(cell => cell === null || (typeof cell === 'string' && !cell.trim()))) continue
    const id = row[identifierColumn], name = row[nameColumn]
    if (typeof id !== 'string' || (name !== undefined && name !== null && typeof name !== 'string')) {
      throw new Error(`Mapping row ${index + 1}: selected cells must be text. Format identifiers as text to preserve leading zeros, and paste names as values.`)
    }
    const identifier = field(applicantIdentifier(field(id, MAPPING_LIMITS.identifierCharacters, 'Applicant identifier')),
      MAPPING_LIMITS.identifierCharacters, 'Applicant identifier')
    if (seen.has(identifier)) throw new Error(`Mapping row ${index + 1}: duplicate applicant identifier. Correct duplicates before downloading, or remove the mapping.`)
    seen.add(identifier)
    result.push({ identifier, name: typeof name === 'string' && name.trim()
      ? field(name, MAPPING_LIMITS.nameCharacters, `Mapping row ${index + 1}: applicant name`) : null })
  }
  return result
}

export function resolveApplicantIdentities(candidates: ReportCandidate[], rows: ApplicantMappingRow[]): ReportApplicantIdentity[] {
  if (rows.length > MAPPING_LIMITS.rows || candidates.length > REPORT_LIMITS.maxComparisons) throw new Error('The applicant mapping exceeds the supported row or candidate limit.')
  const names = new Map<string, string | null>()
  for (const row of rows) {
    const identifier = field(row.identifier, MAPPING_LIMITS.identifierCharacters, 'Applicant identifier')
    if (names.has(identifier)) throw new Error('The local mapping contains duplicate identifiers.')
    names.set(identifier, row.name === null ? null : field(row.name, MAPPING_LIMITS.nameCharacters, 'Applicant name'))
  }
  const byId = new Map<string, ReportApplicantIdentity>()
  const sourceIds = new Map<string, string>()
  for (const candidate of candidates) {
    const urlSource = /^https?:\/\//i.test(candidate.sourceLabel)
    const identifier = field(urlSource ? candidate.id : applicantIdentifier(candidate.sourceLabel), MAPPING_LIMITS.identifierCharacters, 'Source identifier')
    const previous = sourceIds.get(identifier)
    if (previous && previous !== candidate.id) throw new Error('Different resumes share a source identifier in this export. Resolve the ambiguous source filenames or remove the mapping.')
    sourceIds.set(identifier, candidate.id)
    const identity: ReportApplicantIdentity = {
      resumeId: candidate.id, documentId: candidate.documentId, documentVersion: candidate.documentVersion,
      documentSha256: candidate.documentSha256, sourceLabel: candidate.sourceLabel, identifier,
      name: urlSource ? null : names.get(identifier) ?? null,
    }
    const existing = byId.get(candidate.id)
    if (existing && JSON.stringify(existing) !== JSON.stringify(identity)) throw new Error('A resume has inconsistent frozen source identities. Reload the analysis.')
    byId.set(candidate.id, identity)
  }
  return [...byId.values()]
}

export function reportApplicants(report: AnalysisReport): ReportCandidate[] {
  return report.groups.flatMap(group => group.comparisons.filter(item => item.status === 'complete').map(item => item.candidate))
}

export function validateApplicantIdentities(report: AnalysisReport, options?: ReportGenerationOptions): void {
  if (options?.applicantIdentities === undefined) return
  const identities = options.applicantIdentities
  if (!Array.isArray(identities) || identities.length > REPORT_LIMITS.maxComparisons) throw new Error('The local export identities are invalid.')
  const candidates = reportApplicants(report)
  const expected = resolveApplicantIdentities(candidates, [])
  if (identities.length !== expected.length) throw new Error('Local identities do not cover the exact completed export scope.')
  const seen = new Set<string>()
  for (const identity of identities) {
    if (!identity || typeof identity !== 'object' || seen.has(identity.resumeId) ||
      Object.keys(identity).sort().join(',') !== 'documentId,documentSha256,documentVersion,identifier,name,resumeId,sourceLabel') {
      throw new Error('The local export identities contain duplicate or invalid entries.')
    }
    seen.add(identity.resumeId)
    const source = expected.find(item => item.resumeId === identity.resumeId)
    if (!source || Object.entries(source).some(([key, value]) => key !== 'name' && identity[key as keyof ReportApplicantIdentity] !== value) ||
      (identity.name !== null && (typeof identity.name !== 'string' || field(identity.name, MAPPING_LIMITS.nameCharacters, 'Applicant name') !== identity.name))) {
      throw new Error('A local export identity does not match its frozen resume source.')
    }
  }
  assertReportResourceLimits({ report, applicantIdentities: identities }, reportLimits(reportGenerationPolicy(report)).maxInputBytes)
}

export function exportApplicant(candidate: ReportCandidate, options?: ReportGenerationOptions): ReportApplicantIdentity | undefined {
  return options?.applicantIdentities?.find(item => item.resumeId === candidate.id)
}

export function applicantExportName(candidate: ReportCandidate, fallback: string, options?: ReportGenerationOptions): string {
  const identity = exportApplicant(candidate, options)
  return identity ? identity.name ?? identity.identifier : fallback
}

export function applicantExportLabel(candidate: ReportCandidate, fallback: string, options?: ReportGenerationOptions): string {
  const identity = exportApplicant(candidate, options)
  return identity ? identity.name ? `${identity.name}\n${identity.identifier}` : identity.identifier : fallback
}
